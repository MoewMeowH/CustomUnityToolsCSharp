using Microsoft.CodeAnalysis;

namespace HBLint.Generator.Tests;

public class RulesJsonTests
{
    private static GenerateResult Generate(string json) => RulesJson.Generate(json, TestCompiler.RealCatalog);

    [Fact]
    public void 생성물이_기대_텍스트와_같음()
    {
        const string json = """
            {
              "$schema": "../rules.schema.json",
              "rules": [
                { "id": "b-rule", "kind": "BanNullOperator", "type": "B.Type", "message": "mb" },
                {
                  "id": "a-rule",
                  "kind": "BanNullOperator",
                  "description": "첫 줄\n둘째 줄",
                  "severity": "Error",
                  "message": "ma",
                  "type": "A.Type",
                  "requires": ["X", "Y"]
                }
              ]
            }
            """;

        var result = Generate(json);

        Assert.True(result.Success, string.Join("\n", result.Errors));
        Assert.Equal(
            "// <auto-generated>\n" +
            "//     HBLint 생성기(hblint-gen)가 rules.json에서 만들었습니다.\n" +
            "//     직접 고치지 말고 rules.json을 고친 뒤 다시 생성하세요.\n" +
            "// </auto-generated>\n" +
            "\n" +
            "// a-rule\n" +
            "//   첫 줄\n" +
            "//   둘째 줄\n" +
            "[assembly: global::HBLint.BanNullOperatorRule(\"A.Type\", \"ma\", Requires = new string[] { \"X\", \"Y\" }, Severity = global::HBLint.LintSeverity.Error)]\n" +
            "\n" +
            "// b-rule\n" +
            "[assembly: global::HBLint.BanNullOperatorRule(\"B.Type\", \"mb\")]\n",
            result.Text);
    }

    [Fact]
    public void 칸_순서만_다른_입력은_같은_출력()
    {
        var first = Generate("""{"rules":[{"id":"r","kind":"BanNullOperator","type":"T","message":"m","severity":"Info","requires":[]}]}""");
        var second = Generate("""{"rules":[{"requires":[],"severity":"Info","message":"m","type":"T","kind":"BanNullOperator","id":"r"}],"$schema":"x"}""");

        Assert.Equal(first.Text, second.Text);
        Assert.Contains("Requires = new string[0]", first.Text);
    }

    [Fact]
    public void 위험한_문자도_컴파일되고_값이_그대로_돌아옴()
    {
        var nasty = "따옴표\" 역슬래시\\ 줄\r\n탭\t널" + (char)0 + " NEL" + (char)0x85 + " LS" + (char)0x2028 + " PS" + (char)0x2029
                    + " 이모지" + char.ConvertFromUtf32(0x1F600) + " 홀로" + (char)0xD800 + " 끝 */ //";
        var rules = new Json.JsonObject().Add("rules", new Json.JsonArray().Add(new Json.JsonObject()
            .Add("id", new Json.JsonString("nasty"))
            .Add("kind", new Json.JsonString("BanNullOperator"))
            .Add("description", new Json.JsonString(nasty))
            .Add("type", new Json.JsonString(nasty))
            .Add("message", new Json.JsonString(nasty))
            .Add("requires", new Json.JsonArray().Add(new Json.JsonString(nasty)))));

        var result = Generate(Json.JsonWriter.Write(rules));

        Assert.True(result.Success, string.Join("\n", result.Errors));
        var compilation = TestCompiler.Compile("Rules", result.Text!, TestCompiler.Attributes);
        TestCompiler.AssertNoErrors(compilation);
        var attribute = Assert.Single(TestCompiler.AssemblyAttributes(compilation, "HBLint.BanNullOperatorRuleAttribute"));
        Assert.Equal(nasty, attribute.ConstructorArguments[0].Value);
        Assert.Equal(nasty, attribute.ConstructorArguments[1].Value);
        Assert.Equal(nasty, attribute.NamedArguments.Single(a => a.Key == "Requires").Value.Values.Single().Value);
    }

    [Fact]
    public void 새_규칙_종류의_생성물도_컴파일됨()
    {
        const string source = """
            using System;
            namespace HBLint
            {
                public enum Mode { Loose = 0, Strict = 1 }
                [AttributeUsage(AttributeTargets.Assembly, AllowMultiple = true)]
                public sealed class CountLimitRuleAttribute : Attribute
                {
                    public CountLimitRuleAttribute(string target, int limit) { }
                    public bool Enabled { get; set; }
                    public Mode Mode { get; set; }
                }
            }
            """;
        // 진짜 HBLint.Attributes가 시험 참조에 있어 이름을 달리한다 (카탈로그는 어셈블리 이름을 보지 않음)
        var attributes = TestCompiler.Compile("HBLint.Attributes.NewKind", source);
        var catalog = RuleCatalog.FromAssembly(System.Reflection.Assembly.Load(TestCompiler.EmitBytes(attributes)));

        var result = RulesJson.Generate(
            """{"rules":[{"id":"c","kind":"CountLimit","target":"T","limit":-2147483648,"enabled":true,"mode":"Strict"}]}""", catalog);

        Assert.True(result.Success, string.Join("\n", result.Errors));
        Assert.Contains("global::HBLint.CountLimitRule(\"T\", -2147483648, Enabled = true, Mode = global::HBLint.Mode.Strict)", result.Text);
        TestCompiler.AssertNoErrors(TestCompiler.Compile("Rules", result.Text!, TestCompiler.Emit(attributes)));
    }

    [Fact]
    public void 키워드_이름의_enum_멤버와_속성은_골뱅이를_붙여_컴파일됨()
    {
        const string source = """
            namespace HBLint
            {
                public enum Pick { @default = 0, @class = 1 }
                [System.AttributeUsage(System.AttributeTargets.Assembly)]
                public sealed class KeywordRuleAttribute : System.Attribute
                {
                    public KeywordRuleAttribute(string name) { }
                    public bool @event { get; set; }
                    public Pick Pick { get; set; }
                }
            }
            """;
        var attributes = TestCompiler.Compile("HBLint.Attributes.Keyword", source);
        var catalog = RuleCatalog.FromAssembly(System.Reflection.Assembly.Load(TestCompiler.EmitBytes(attributes)));

        var result = RulesJson.Generate("""{"rules":[{"id":"k","kind":"Keyword","name":"n","event":true,"pick":"class"}]}""", catalog);

        Assert.True(result.Success, string.Join("\n", result.Errors));
        // 속성은 이름 순(ordinal)이라 Pick이 event보다 앞
        Assert.Contains("Pick = global::HBLint.Pick.@class, @event = true", result.Text);
        TestCompiler.AssertNoErrors(TestCompiler.Compile("Rules", result.Text!, TestCompiler.Emit(attributes)));
    }

    [Fact]
    public void AllowMultiple이_false인_종류는_두_번_쓰면_오류()
    {
        var assembly = TestCompiler.LoadAttributes("""
            namespace HBLint
            {
                [System.AttributeUsage(System.AttributeTargets.Assembly)]
                public sealed class OnceRuleAttribute : System.Attribute { public OnceRuleAttribute(string name) { } }
            }
            """);
        var catalog = RuleCatalog.FromAssembly(assembly);

        var once = RulesJson.Generate("""{"rules":[{"id":"a","kind":"Once","name":"x"}]}""", catalog);
        var twice = RulesJson.Generate("""{"rules":[{"id":"a","kind":"Once","name":"x"},{"id":"b","kind":"Once","name":"y"}]}""", catalog);

        Assert.True(once.Success);
        Assert.False(twice.Success);
        var error = Assert.Single(twice.Errors);
        Assert.Equal("b", error.RuleId);
        Assert.Contains("한 번만", error.Message);
        Assert.True(TestCompiler.RealCatalog.Kinds.Single().AllowMultiple);
    }

    [Fact]
    public void 다른_오류가_있는_규칙의_id_중복도_보임()
    {
        var result = Generate("""
            {"rules":[
              {"id":"same","kind":"BanNullOperator","type":"T","message":"m"},
              {"id":"same","kind":"BanNullOperator"}
            ]}
            """);

        Assert.Contains(result.Errors, e => e.RuleId == "same" && e.Message.Contains("두 번"));
        Assert.Contains(result.Errors, e => e.RuleId == "same" && e.Message.Contains("'type'"));
    }

    [Fact]
    public void 오류를_한꺼번에_모으고_생성하지_않음()
    {
        const string json = """
            {
              "rules": [
                { "id": "ok", "kind": "BanNullOperator", "type": "T", "message": "m" },
                { "id": "dup", "kind": "BanNullOperator", "type": "T", "message": "m" },
                { "id": "dup", "kind": "BanNullOperator", "type": "T", "message": "m" },
                { "id": "bad id!", "kind": "BanNullOperator", "type": "T", "message": "m" },
                { "id": "unknown-kind", "kind": "Nope" },
                { "id": "missing", "kind": "BanNullOperator", "type": "T" },
                { "id": "wrong-types", "kind": "BanNullOperator", "type": 1, "message": "m", "requires": ["a", 2], "severity": "warning" },
                { "id": "extra", "kind": "BanNullOperator", "type": "T", "message": "m", "Type": "T2" },
                { "kind": "BanNullOperator", "type": "T", "message": "m" },
                "not an object"
              ],
              "other": 1
            }
            """;

        var result = Generate(json);

        Assert.False(result.Success);
        Assert.Null(result.Text);
        var messages = result.Errors.Select(e => e.ToString()).ToList();
        Assert.Contains(messages, m => m.Contains("[dup]") && m.Contains("두 번"));
        Assert.Contains(messages, m => m.Contains("[bad id!]") && m.Contains("형식"));
        Assert.Contains(messages, m => m.Contains("[unknown-kind]") && m.Contains("모르는 kind 'Nope'") && m.Contains("BanNullOperator"));
        Assert.Contains(messages, m => m.Contains("[missing]") && m.Contains("'message'"));
        Assert.Contains(messages, m => m.Contains("[wrong-types]") && m.Contains("'type'은(는) 문자열"));
        Assert.Contains(messages, m => m.Contains("[wrong-types]") && m.Contains("'requires'의 항목"));
        Assert.Contains(messages, m => m.Contains("[wrong-types]") && m.Contains("'warning'") && m.Contains("Warning"));
        Assert.Contains(messages, m => m.Contains("[extra]") && m.Contains("없는 칸 'Type'"));
        Assert.Contains(messages, m => m.Contains("필수 칸 'id'"));
        Assert.Contains(messages, m => m.Contains("규칙은 객체"));
        Assert.Contains(messages, m => m.Contains("모르는 칸 'other'"));
        Assert.All(result.Errors, e => Assert.True(e.Line > 0 && e.Column > 0));
    }

    [Theory]
    [InlineData("[]", "맨 바깥은 객체")]
    [InlineData("{}", "\"rules\" 배열이 없습니다")]
    [InlineData("{\"rules\": {}}", "배열이어야")]
    [InlineData("{\"rules\": [], \"$schema\": 1}", "\"$schema\"는 문자열")]
    [InlineData("{\"rules\": [}", "JSON 형식 오류")]
    public void 바깥_구조_오류(string json, string expected)
    {
        var result = Generate(json);

        Assert.False(result.Success);
        Assert.Contains(result.Errors, e => e.Message.Contains(expected));
    }

    [Theory]
    [InlineData("1.5")]
    [InlineData("2147483648")]
    [InlineData("1e3")]
    public void int_칸은_int_범위_정수만(string number)
    {
        var assembly = TestCompiler.LoadAttributes("""
            namespace HBLint
            {
                [System.AttributeUsage(System.AttributeTargets.Assembly)]
                public sealed class LimitRuleAttribute : System.Attribute { public LimitRuleAttribute(int limit) { } }
            }
            """);

        var result = RulesJson.Generate($$"""{"rules":[{"id":"l","kind":"Limit","limit":{{number}}}]}""", RuleCatalog.FromAssembly(assembly));

        Assert.False(result.Success);
        Assert.Contains("int 범위의 정수", Assert.Single(result.Errors).Message);
    }

    [Fact]
    public void 규칙이_없으면_머리_주석만()
    {
        var result = Generate("""{"rules":[]}""");

        Assert.True(result.Success);
        Assert.DoesNotContain("[assembly:", result.Text);
        TestCompiler.AssertNoErrors(TestCompiler.Compile("Rules", result.Text!, TestCompiler.Attributes));
    }
}
