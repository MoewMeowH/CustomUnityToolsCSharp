using System.Globalization;
using System.Text.RegularExpressions;
using HBLint.Core.Generation;
using HBLint.Core.Ir;
using HBLint.Core.Json;

namespace HBLint.App;

/// <summary>
/// 연 규칙 폴더. 그 폴더 바로 아래의 *.hblint.json만 읽고 쓴다 (CLI와 같은 범위) — 이름에 경로 구분자 · ..가 들어가면 거절하고,
/// 심볼릭 링크면 실제 자리가 폴더 바로 아래인지 다시 본다. 지우기 · 이름 바꾸기는 하지 않는다.
/// </summary>
internal sealed partial class RuleFolder
{
    // 글자(한글 포함) · 숫자 · _ . - 만. \z — $는 끝의 \n 앞에서도 맞는다
    [GeneratedRegex(@"^[\p{L}\p{N}_.-]+\.hblint\.json\z")]
    private static partial Regex FileName();

    public RuleFolder(string folder, string output)
    {
        Folder = Path.TrimEndingDirectorySeparator(Path.GetFullPath(folder));
        Output = Path.GetFullPath(output);
    }

    public string Folder { get; }

    /// <summary>생성물 LintRules.g.cs — 열 때 정한 이 경로에만 쓴다.</summary>
    public string Output { get; }

    public static bool IsRuleFileName(string name) => FileName().IsMatch(name) && !name.Contains("..", StringComparison.Ordinal);

    /// <summary>폴더 안 규칙 파일 경로. 이름이 틀렸거나 폴더 밖을 가리키면 null.</summary>
    public string? PathOf(string name)
    {
        if (!IsRuleFileName(name))
            return null;
        var path = Path.Combine(Folder, name);
        if (!string.Equals(Path.GetDirectoryName(Path.GetFullPath(path)), Folder, StringComparison.OrdinalIgnoreCase))
            return null;
        if (File.Exists(path) && File.ResolveLinkTarget(path, returnFinalTarget: true) is { } target
            && !string.Equals(Path.GetDirectoryName(target.FullName), Folder, StringComparison.OrdinalIgnoreCase))
            return null;
        return path;
    }

    /// <summary>생성(= CLI)이 읽는 파일 전부. 앱에서 열 수 없는 것(이름 규칙 밖 · 폴더 밖 링크)도 보이되 Editable이 false.</summary>
    public IReadOnlyList<RuleSummary> List()
    {
        var result = new List<RuleSummary>();
        foreach (var file in RuleSet.ReadFolder(Folder))
        {
            var name = Path.GetFileName(file.Path);
            var parsed = RuleIr.Parse(file.Text);
            string? title = null;
            try
            {
                title = (JsonReader.Parse(file.Text) as JsonObject)?.Get("title") is JsonString s ? s.Value : null;
            }
            catch (JsonParseException)
            {
            }
            result.Add(new RuleSummary(name, parsed.Id, title, parsed.Errors.Count(e => !e.IsWarning), parsed.Errors.Count(e => e.IsWarning), PathOf(name) != null));
        }
        // id 숫자 순 (파일 이름 글자 순이면 rule10이 rule2 앞에 온다), id가 없거나 잘못된 파일은 뒤, 같으면 파일 이름 순
        return result
            .OrderBy(r => IdNumber(r.Id) ?? int.MaxValue)
            .ThenBy(r => r.File, StringComparer.Ordinal)
            .ToList();
    }

    private static int? IdNumber(string? id) =>
        id != null && RuleIds.IsRuleId(id) ? int.Parse(id.AsSpan(RuleIds.Prefix.Length), NumberStyles.None, CultureInfo.InvariantCulture) : null;

    /// <summary>폴더 안 가장 큰 id + 1 (빈 번호는 채우지 않는다 — 지운 규칙의 id를 다시 쓰지 않게). 다 찼으면 null.</summary>
    public string? NextId(IEnumerable<RuleSummary> rules)
    {
        var max = RuleIds.First - 1;
        foreach (var rule in rules)
        {
            if (IdNumber(rule.Id) is { } number)
                max = Math.Max(max, number);
        }
        return max + 1 <= RuleIds.Last ? RuleIds.Format(max + 1) : null;
    }

    /// <summary>JSON이면 CLI와 같은 모양(JsonWriter — 키 순서 유지 · LF)으로 쓴다. 검증 오류가 있어도 쓴다 (만들다 만 규칙).</summary>
    public static string Normalize(string text) => JsonWriter.Write(JsonReader.Parse(text));

    /// <summary>생성물 머리 — RuleSet이 쓰는 첫 줄과 도구 이름.</summary>
    private const string GeneratedHeader = "// <auto-generated>";

    /// <summary>
    /// CLI generate와 같은 결과. 생성물 자리에 이미 파일이 있는데 hblint-gen 생성물이 아니면(경로를 잘못 넣어 손으로 쓴 .cs를 가리킴) 쓰지 않고 까닭을 돌려준다.
    /// </summary>
    public (RuleSet Set, string? Refused) Generate()
    {
        var set = RuleSet.Build(RuleSet.ReadFolder(Folder));
        if (set.Text == null)
            return (set, null);
        if (File.Exists(Output) && !IsGeneratedFile(Output))
            return (set, $"{Output}은(는) hblint-gen 생성물이 아니라 덮지 않았습니다 — 생성물 경로를 확인하세요");
        OutputFile.WriteIfChanged(Output, set.Text);
        return (set, null);
    }

    /// <summary>hblint-gen이 쓴 생성물인가 (첫 줄 머리 + 도구 이름).</summary>
    public static bool IsGeneratedFile(string path)
    {
        // StreamReader가 BOM을 떼고 읽는다
        using var reader = new StreamReader(path);
        var head = new char[512];
        var text = new string(head, 0, reader.ReadBlock(head, 0, head.Length));
        return text.StartsWith(GeneratedHeader, StringComparison.Ordinal) && text.Contains("hblint-gen", StringComparison.Ordinal);
    }
}

internal sealed record RuleSummary(string File, string? Id, string? Title, int Errors, int Warnings, bool Editable = true);
