#nullable enable
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using HBLint.Core.Ir;

namespace HBLint.Core.Generation
{
    /// <summary>규칙 파일 하나 (경로는 오류 메시지 · 생성물 주석용).</summary>
    internal sealed class RuleFile
    {
        public RuleFile(string path, string text)
        {
            Path = path;
            Text = text;
        }

        public string Path { get; }

        public string Text { get; }
    }

    /// <summary>규칙 폴더의 규칙 파일들 → 검증 → LintRules.g.cs. 오류가 하나라도 있으면 Text가 없다.</summary>
    internal sealed class RuleSet
    {
        public const string FilePattern = "*.hblint.json";

        private RuleSet(List<string> errors, List<string> warnings, string? text, int count)
        {
            Errors = errors;
            Warnings = warnings;
            Text = text;
            Count = count;
        }

        /// <summary>"경로(줄,칸): 내용".</summary>
        public IReadOnlyList<string> Errors { get; }

        public IReadOnlyList<string> Warnings { get; }

        /// <summary>LintRules.g.cs 내용 (오류가 없을 때만).</summary>
        public string? Text { get; }

        public int Count { get; }

        /// <summary>폴더 바로 아래의 *.hblint.json (하위 폴더는 보지 않음 — 생성물 · asmdef 폴더와 섞이지 않게).</summary>
        public static IReadOnlyList<RuleFile> ReadFolder(string folder) =>
            Directory.GetFiles(folder, FilePattern, SearchOption.TopDirectoryOnly)
                .OrderBy(p => p, System.StringComparer.Ordinal)
                .Select(p => new RuleFile(p, File.ReadAllText(p)))
                .ToList();

        public static RuleSet Build(IReadOnlyList<RuleFile> files)
        {
            var errors = new List<string>();
            var warnings = new List<string>();
            var rules = new List<(RuleFile File, RuleIr Rule)>();
            foreach (var file in files)
            {
                var parsed = RuleIr.Parse(file.Text);
                foreach (var error in parsed.Errors)
                    (error.IsWarning ? warnings : errors).Add(file.Path + error);
                if (parsed.Rule != null)
                    rules.Add((file, parsed.Rule));
            }

            foreach (var group in rules.GroupBy(r => r.Rule.Id).Where(g => g.Count() > 1))
                errors.Add($"{string.Join(" · ", group.Select(r => r.File.Path))}: 규칙 id {group.Key}가 여러 파일에 있습니다");

            if (errors.Count > 0)
                return new RuleSet(errors, warnings, null, rules.Count);
            return new RuleSet(errors, warnings, Write(rules), rules.Count);
        }

        /// <summary>id 순 · LF · 규칙마다 주석(id · 파일 이름 · 제목)과 어트리뷰트 한 줄.</summary>
        private static string Write(List<(RuleFile File, RuleIr Rule)> rules)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated>\n");
            sb.Append("//     hblint-gen이 규칙 파일(*.hblint.json)에서 만들었습니다.\n");
            sb.Append("//     직접 고치지 말고 규칙 파일을 고친 뒤 다시 생성하세요.\n");
            sb.Append("// </auto-generated>\n");
            foreach (var (file, rule) in rules.OrderBy(r => r.Rule.Id, System.StringComparer.Ordinal))
            {
                sb.Append('\n');
                sb.Append("// ").Append(rule.Id).Append(' ').Append(OneLine(System.IO.Path.GetFileName(file.Path)));
                if (rule.Title.Length > 0)
                    sb.Append(" — ").Append(OneLine(rule.Title));
                sb.Append('\n');
                sb.Append("[assembly: global::HBLint.Rule(").Append(CSharpString(rule.ToRuntimeJson())).Append(")]\n");
            }
            return sb.ToString();
        }

        /// <summary>C# 일반 문자열 리터럴. 줄을 끊는 글자(제어 문자 · U+0085 · U+2028 · U+2029)는 \u로.</summary>
        internal static string CSharpString(string value)
        {
            var sb = new StringBuilder(value.Length + 2);
            sb.Append('"');
            foreach (var c in value)
            {
                switch (c)
                {
                    case '"': sb.Append("\\\""); break;
                    case '\\': sb.Append("\\\\"); break;
                    default:
                        if (c < 0x20 || c == 0x7F || c == 0x85 || c == 0x2028 || c == 0x2029)
                            sb.Append("\\u").Append(((int)c).ToString("x4"));
                        else
                            sb.Append(c);
                        break;
                }
            }
            sb.Append('"');
            return sb.ToString();
        }

        /// <summary>주석 한 줄에 넣을 글 — 줄을 끊는 글자는 공백으로.</summary>
        private static string OneLine(string value)
        {
            var chars = value.ToCharArray();
            for (var i = 0; i < chars.Length; i++)
            {
                var c = chars[i];
                if (c < 0x20 || c == 0x85 || c == 0x2028 || c == 0x2029)
                    chars[i] = ' ';
            }
            return new string(chars);
        }
    }
}
