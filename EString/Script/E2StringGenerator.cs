using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace EString.Script
{
    [Generator]
    public class E2StringGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context)
        {
            context.RegisterForSyntaxNotifications(() => new EnumSyntaxReceiver());
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (!(context.SyntaxReceiver is EnumSyntaxReceiver receiver))
                return;

            foreach (var enumDeclaration in receiver.CandidateEnums)
            {
                if (!HasTargetAttribute(enumDeclaration))
                {
                    continue;
                }

                var sourceCode = GenerateExtensionClass(enumDeclaration);
                var fullTypeName = GetFullTypeName(enumDeclaration);
                var safeFileName = fullTypeName.Replace(".", "_");
                var fileName = $"{safeFileName}_Extensions.g.cs";

                context.AddSource(fileName, SourceText.From(sourceCode, Encoding.UTF8));
            }
        }

        private static bool HasTargetAttribute(EnumDeclarationSyntax enumDeclaration)
        {
            foreach (var attributeList in enumDeclaration.AttributeLists)
            {
                foreach (var attribute in attributeList.Attributes)
                {
                    var name = attribute.Name.ToString();
                    if (name.EndsWith("E2String") || name.EndsWith("E2StringAttribute"))
                    {
                        return true;
                    }
                }
            }
            return false;
        }

        private static string GenerateExtensionClass(EnumDeclarationSyntax enumDeclaration)
        {
            var sb = new StringBuilder();

            var enumName = enumDeclaration.Identifier.Text;
            var fullTypeName = GetFullTypeName(enumDeclaration);
            var safeClassName = fullTypeName.Replace(".", "_");
            var members = enumDeclaration.Members;
            var memberCount = members.Count;

            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine();

            string nameSpace = GetNamespace(enumDeclaration);
            if (!string.IsNullOrEmpty(nameSpace))
            {
                sb.AppendLine($"namespace {nameSpace}");
                sb.AppendLine("{");
            }

            string indent = string.IsNullOrEmpty(nameSpace) ? "" : "    ";

            sb.AppendLine($"{indent}public static class {safeClassName}Extensions");
            sb.AppendLine($"{indent}{{");

            // 1. All Count
            sb.AppendLine($"{indent}    /// <summary>전체 Enum 항목 개수</summary>");
            sb.AppendLine($"{indent}    public const int Count = {memberCount};");
            sb.AppendLine();

            // 2. All Names
            sb.AppendLine($"{indent}    /// <summary>모든 Enum 식별자 이름 배열</summary>");
            sb.AppendLine($"{indent}    public static readonly string[] Names = new string[]");
            sb.AppendLine($"{indent}    {{");
            foreach (var member in members)
            {
                sb.AppendLine($"{indent}        \"{member.Identifier.Text}\",");
            }
            sb.AppendLine($"{indent}    }};");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>모든 Enum 식별자 이름 읽기 전용 컬렉션</summary>");
            sb.AppendLine($"{indent}    public static System.Collections.Generic.IReadOnlyList<string> AllNames => Names;");
            sb.AppendLine();

            // 3. All Values
            sb.AppendLine($"{indent}    /// <summary>모든 Enum 값 배열</summary>");
            sb.AppendLine($"{indent}    public static readonly {fullTypeName}[] Values = new {fullTypeName}[]");
            sb.AppendLine($"{indent}    {{");
            foreach (var member in members)
            {
                sb.AppendLine($"{indent}        {fullTypeName}.{member.Identifier.Text},");
            }
            sb.AppendLine($"{indent}    }};");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>모든 Enum 값 읽기 전용 컬렉션</summary>");
            sb.AppendLine($"{indent}    public static System.Collections.Generic.IReadOnlyList<{fullTypeName}> AllValues => Values;");
            sb.AppendLine();

            // 4. Enum -> String
            sb.AppendLine($"{indent}    #region Enum -> String");
            sb.AppendLine($"{indent}    /// <summary>Enum 값을 무할당(Zero-Allocation) 문자열로 고속 변환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static string ToStringFast(this {fullTypeName} value, string? fallback = null)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return value switch");
            sb.AppendLine($"{indent}        {{");
            foreach (var member in members)
            {
                var memberName = member.Identifier.Text;
                sb.AppendLine($"{indent}            {fullTypeName}.{memberName} => \"{memberName}\",");
            }
            sb.AppendLine($"{indent}            _ => fallback ?? value.ToString()");
            sb.AppendLine($"{indent}        }};");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();

            // 5. String -> Enum
            sb.AppendLine($"{indent}    #region String -> Enum");
            sb.AppendLine($"{indent}    /// <summary>문자열을 Enum으로 고속 변환합니다. 일치하지 않으면 fallback을 반환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static {fullTypeName} To{enumName}(this string? value, {fullTypeName} fallback = default)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return value switch");
            sb.AppendLine($"{indent}        {{");
            foreach (var member in members)
            {
                var memberName = member.Identifier.Text;
                sb.AppendLine($"{indent}            \"{memberName}\" => {fullTypeName}.{memberName},");
            }
            sb.AppendLine($"{indent}            _ => fallback");
            sb.AppendLine($"{indent}        }};");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>문자열을 Enum으로 안전하게 파싱합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static bool TryParseFast(string? value, out {fullTypeName} result, {fullTypeName} fallback = default)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        switch (value)");
            sb.AppendLine($"{indent}        {{");
            foreach (var member in members)
            {
                var memberName = member.Identifier.Text;
                sb.AppendLine($"{indent}            case \"{memberName}\":");
                sb.AppendLine($"{indent}                result = {fullTypeName}.{memberName};");
                sb.AppendLine($"{indent}                return true;");
            }
            sb.AppendLine($"{indent}            default:");
            sb.AppendLine($"{indent}                result = fallback;");
            sb.AppendLine($"{indent}                return false;");
            sb.AppendLine($"{indent}        }}");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();

            // 6. Enum <-> Int (Unity 2021.3+ UnsafeUtility vs Explicit Cast 분기)
            sb.AppendLine($"{indent}    #region Enum <-> Int");
            sb.AppendLine($"{indent}#if UNITY_2021_3_OR_NEWER");
            sb.AppendLine($"{indent}    /// <summary>Unity 2021.3+ UnsafeUtility.As를 통해 박싱 및 오버헤드 없이 int로 변환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static int ToInt(this {fullTypeName} value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return Unity.Collections.LowLevel.Unsafe.UnsafeUtility.As<{fullTypeName}, int>(ref value);");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>Unity 2021.3+ UnsafeUtility.As를 통해 박싱 및 오버헤드 없이 int로 변환합니다. (ToInt 동일)</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static int ToIntFast(this {fullTypeName} value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return Unity.Collections.LowLevel.Unsafe.UnsafeUtility.As<{fullTypeName}, int>(ref value);");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>int 값을 유효성 검사 후 Enum으로 안전하게 변환합니다. 유효하지 않으면 fallback을 반환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static {fullTypeName} To{enumName}(this int value, {fullTypeName} fallback = default)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        if (IsDefined(value))");
            sb.AppendLine($"{indent}        {{");
            sb.AppendLine($"{indent}            return Unity.Collections.LowLevel.Unsafe.UnsafeUtility.As<int, {fullTypeName}>(ref value);");
            sb.AppendLine($"{indent}        }}");
            sb.AppendLine($"{indent}        return fallback;");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>검사 없이 UnsafeUtility를 통해 int를 Enum으로 즉각 변환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static {fullTypeName} To{enumName}Fast(this int value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return Unity.Collections.LowLevel.Unsafe.UnsafeUtility.As<int, {fullTypeName}>(ref value);");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}#else");
            sb.AppendLine($"{indent}    /// <summary>명시적 캐스팅(Explicit Cast)을 통해 박싱 없이 int로 변환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static int ToInt(this {fullTypeName} value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return (int)value;");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>명시적 캐스팅(Explicit Cast)을 통해 박싱 없이 int로 변환합니다. (ToInt 동일)</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static int ToIntFast(this {fullTypeName} value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return (int)value;");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>int 값을 유효성 검사 후 Enum으로 안전하게 변환합니다. 유효하지 않으면 fallback을 반환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static {fullTypeName} To{enumName}(this int value, {fullTypeName} fallback = default)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return IsDefined(value) ? ({fullTypeName})value : fallback;");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>검사 없이 명시적 캐스팅을 통해 int를 Enum으로 즉각 변환합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static {fullTypeName} To{enumName}Fast(this int value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return ({fullTypeName})value;");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}#endif");
            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();

            // 7. IsDefined Fast
            sb.AppendLine($"{indent}    #region IsDefined Fast");
            sb.AppendLine($"{indent}    /// <summary>Enum 값이 정의된 유효한 값인지 고속 검사합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static bool IsDefined({fullTypeName} value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return value switch");
            sb.AppendLine($"{indent}        {{");
            foreach (var member in members)
            {
                var memberName = member.Identifier.Text;
                sb.AppendLine($"{indent}            {fullTypeName}.{memberName} => true,");
            }
            sb.AppendLine($"{indent}            _ => false");
            sb.AppendLine($"{indent}        }};");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
            sb.AppendLine($"{indent}    /// <summary>정수 값이 정의된 유효한 Enum 값인지 고속 검사합니다.</summary>");
            sb.AppendLine($"{indent}    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"{indent}    public static bool IsDefined(int value)");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}#if UNITY_2021_3_OR_NEWER");
            sb.AppendLine($"{indent}        var enumVal = Unity.Collections.LowLevel.Unsafe.UnsafeUtility.As<int, {fullTypeName}>(ref value);");
            sb.AppendLine($"{indent}        return IsDefined(enumVal);");
            sb.AppendLine($"{indent}#else");
            sb.AppendLine($"{indent}        return IsDefined(({fullTypeName})value);");
            sb.AppendLine($"{indent}#endif");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    #endregion");

            sb.AppendLine($"{indent}}}");

            if (!string.IsNullOrEmpty(nameSpace))
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }

        private static string GetFullTypeName(EnumDeclarationSyntax enumDeclaration)
        {
            string fullTypeName = enumDeclaration.Identifier.Text;
            SyntaxNode? parent = enumDeclaration.Parent;

            while (parent != null)
            {
                if (parent is ClassDeclarationSyntax classDecl)
                {
                    fullTypeName = $"{classDecl.Identifier.Text}.{fullTypeName}";
                }
                else if (parent is StructDeclarationSyntax structDecl)
                {
                    fullTypeName = $"{structDecl.Identifier.Text}.{fullTypeName}";
                }
                else if (parent is NamespaceDeclarationSyntax)
                {
                    break;
                }

                parent = parent.Parent;
            }

            return fullTypeName;
        }

        private static string GetNamespace(SyntaxNode syntaxNode)
        {
            var parent = syntaxNode.Parent;
            string finalNamespace = "";

            while (parent != null)
            {
                if (parent is NamespaceDeclarationSyntax namespaceDeclaration)
                {
                    if (string.IsNullOrEmpty(finalNamespace))
                    {
                        finalNamespace = namespaceDeclaration.Name.ToString();
                    }
                    else
                    {
                        finalNamespace = $"{namespaceDeclaration.Name}.{finalNamespace}";
                    }
                }
                parent = parent.Parent;
            }

            return finalNamespace;
        }
    }

    internal class EnumSyntaxReceiver : ISyntaxReceiver
    {
        public System.Collections.Generic.List<EnumDeclarationSyntax> CandidateEnums { get; }
            = new System.Collections.Generic.List<EnumDeclarationSyntax>();

        public void OnVisitSyntaxNode(SyntaxNode syntaxNode)
        {
            if (syntaxNode is EnumDeclarationSyntax enumDeclaration &&
                enumDeclaration.AttributeLists.Count > 0)
            {
                CandidateEnums.Add(enumDeclaration);
            }
        }
    }
}
